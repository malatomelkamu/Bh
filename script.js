function createDefaultUserRecord(type, payload = {}) {
  return {
    id: crypto.randomUUID ? crypto.randomUUID() : `id-${Date.now()}-${Math.random().toString(16).slice(2)}`,
    type,
    name: payload.name || '',
    grade: payload.grade || '',
    stream: payload.stream || '',
    section: payload.section || '',
    telegramHandle: payload.telegramHandle || '',
    userId: payload.userId || '',
    firstName: payload.firstName || '',
    avatar: payload.avatar || '',
    hasJoined: !!payload.hasJoined,
    joinedAt: payload.joinedAt || null
  };
}

function ensureUserRecord(type, payload) {
  let existing = findUserByName(payload.name);
  if (!existing) {
    existing = createDefaultUserRecord(type, payload);
    state.users.push(existing);
  }

  existing.type = type;
  existing.name = payload.name;
  existing.grade = payload.grade || existing.grade;
  existing.stream = payload.stream || existing.stream;
  existing.section = payload.section || existing.section;
  existing.telegramHandle = payload.telegramHandle || existing.telegramHandle;
  existing.userId = payload.userId || existing.userId;
  existing.firstName = payload.firstName || existing.firstName;
  existing.avatar = payload.avatar || existing.avatar;
  existing.hasJoined = typeof payload.hasJoined === 'boolean' ? payload.hasJoined : existing.hasJoined;
  existing.joinedAt = payload.joinedAt || existing.joinedAt;

  saveState();
  return existing;
}

